/** [目录上的栏目名（第一单元 / 综合实践 / 数学好玩 / 总复习）, 单元名（总复习没有）, 页码] */
type U = [label: string, title: string | null, page: number, note?: string];

function units(volId: string, rows: U[]): Unit[] {
  return rows.map(([label, title, page, note], i) => ({
    id: `${volId}.u${i}`,
    order: i,
    title: title ? `${label} ${title}` : label,
    page,
    ...(note ? { note } : {}),
    provenance: 'verified' as const,
    lessons: [],
    kpIds: [],
    bankUnitIds: [],
  }));
}

