/**
 * 一～六年级语文知识点（本项目原创编写）。
 *
 * 以统编版小学语文（人民教育出版社出版）公开的单元主题为单位，即题库 ChinaStudyFree 中的单元划分；
 * 每个单元作为一个知识点，“能做什么”与单元之间的联系由本项目编写。
 * 语文能力的发展不像数学那样有严格的先后，所以大部分先修关系是 soft（有帮助），
 * 只有汉语拼音 → 借助拼音阅读这类关系标为 hard。
 * 未核对教材原文与各单元的语文要素；未经一线教师审核。期末归纳单元不单独设知识点。
 */
import type { KnowledgePoint, Strength } from '../graph';

type P = [string, Strength, string];

function C(
  grade: number,
  term: '上' | '下',
  unit: number,
  name: string,
  kid: [string, string?],
  emoji: string,
  canDo: string,
  prereqs: P[] = [],
): KnowledgePoint {
  const t = term === '上' ? 'a' : 'b';
  return {
    id: `c${grade}.${t}${unit}`,
    subject: 'chinese',
    name: `${grade}${term}·${name}`,
    kidName: kid[0],
    kidPy: kid[1],
    emoji,
    grade,
    term,
    order: (term === '上' ? 0 : 50) + unit,
    canDo,
    prerequisites: prereqs.map(([id, strength, why]) => ({ id, strength, why })),
    practicable: false,
    units: [`chinese-g${grade}${t}-u${unit}`],
  };
}
