import type { KnowledgePoint, Strength } from '../graph';

type P = [string, Strength, string];
const pre = (xs: P[]) => xs.map(([id, strength, why]) => ({ id, strength, why }));

function M(
  id: string,
  grade: number,
  term: '上' | '下',
  unit: number,
  name: string,
  kid: [string, string?],
  emoji: string,
  canDo: string,
  prereqs: P[] = [],
): KnowledgePoint {
  return {
    id,
    subject: 'math',
    name,
    kidName: kid[0],
    kidPy: kid[1],
    emoji,
    grade,
    term,
    order: (term === '上' ? 0 : 50) + unit,
    canDo,
    prerequisites: pre(prereqs),
    practicable: false, // 由 graph.ts 根据“有生成器或有题库单元”统一计算
    units: [`math-g${grade}${term === '上' ? 'a' : 'b'}-u${unit}`],
  };
}

