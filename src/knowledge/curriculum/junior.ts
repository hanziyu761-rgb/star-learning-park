import type { KnowledgePoint, Strength } from '../graph';

type P = [string, Strength, string];
const pre = (xs: P[]) => xs.map(([id, strength, why]) => ({ id, strength, why }));

function J(
  subject: 'math' | 'chinese' | 'english',
  grade: number,
  term: '上' | '下',
  unit: number,
  name: string,
  emoji: string,
  canDo: string,
  prereqs: P[] = [],
  units: string[] = [],
): KnowledgePoint {
  const t = term === '上' ? 'a' : 'b';
  return {
    id: `${subject[0]}${grade}.${t}${unit}`,
    subject,
    name: subject === 'math' ? name : `${grade}${term}·${name}`,
    kidName: name,
    emoji,
    grade,
    term,
    order: (term === '上' ? 0 : 50) + unit,
    canDo,
    prerequisites: pre(prereqs),
    practicable: true,
    units,
  };
}
