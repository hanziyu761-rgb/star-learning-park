type Rand = () => number;
type Built = ReturnType<UpperGen['build']>;
const pickI = (rand: Rand, n: number) => Math.floor(rand() * n);
const zhSay = (text: string) => ({ text, lang: 'zh-CN' as const });
const enSay = (text: string) => ({ text, lang: 'en-US' as const });

/** 选项顺序由签名决定（同一道题每次一样），正确答案不总在第一个 */
function arrange(answer: string, wrongs: string[], seed: number): string[] {
  const all = [...new Set([answer, ...wrongs.filter((w) => w && w !== answer)])].slice(0, 4);
  const k = seed % all.length;
  return [...all.slice(k), ...all.slice(0, k)];
}

/* ═══════════════ 语文 ═══════════════ */

/** 每行：题目|答案|干扰项（用 / 分隔）|讲解 */
function zhPool(lines: string): UpperGen & { n: number } {
  const items = lines
    .trim()
    .split('\n')
    .map((l) => l.trim().split('|'));
  for (const it of items) if (it.length !== 4) throw new Error(`语文题格式错误：${it.join('|')}`);
  return {
    n: items.length,
    make: (rand) => `z:${pickI(rand, items.length)}`,
    build: (sig) => {
      const i = Number(sig.split(':')[1]);
      const [q, ans, wrongs, ex] = items[i];
      const list = arrange(ans, wrongs.split('/'), i * 7 + 3);
      return {
        prompt: { text: q, speak: zhSay(q) },
        options: list.map((t) => ({ id: t, text: t, speak: zhSay(t) })),
        answerId: ans,
        explanation: ex,
        wrongHint: { text: '再想一想', speak: zhSay('再想一想') },
      };
    },
  };
}

