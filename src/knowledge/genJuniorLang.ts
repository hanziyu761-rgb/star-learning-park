type EnItem = { stem: string; ans: string; wrongs: string[]; ex: string };
function enBuilt(it: EnItem, seed: number, prompt = 'Choose the best answer.'): Built {
  const list = arrange(it.ans, it.wrongs, seed);
  return {
    prompt: { text: prompt, speak: enSay(prompt), hintZh: '选出正确答案' },
    stem: { text: it.stem },
    options: list.map((t) => ({ id: t, text: t, speak: enSay(t) })),
    answerId: it.ans,
    explanation: it.ex,
    wrongHint: { text: 'Try again.', speak: enSay('Try again.') },
  };
}
/** 模板题：签名 t:模板编号:主语:动作 */
function enTemplate(templates: ((s: (typeof SUBJECTS)[number], a: (typeof ACTS)[number]) => EnItem)[]): UpperGen {
  return {
    make: (rand) => `t:${pickI(rand, templates.length)}:${pickI(rand, SUBJECTS.length)}:${pickI(rand, ACTS.length)}`,
    build: (sig) => {
      const [, t, s, a] = sig.split(':').map(Number);
      return enBuilt(templates[t](SUBJECTS[s], ACTS[a]), t + s + a);
    },
  };
}
/** 每行：题目（空格处写 ___）|答案|干扰项（用 / 分隔）|中文讲解 */
function enPool(lines: string): UpperGen {
  const items = lines
    .trim()
    .split('\n')
    .map((l) => l.trim().split('|'));
  for (const it of items) if (it.length !== 4) throw new Error(`英语题格式错误：${it.join('|')}`);
  return {
    make: (rand) => `p:${pickI(rand, items.length)}`,
    build: (sig) => {
      const i = Number(sig.split(':')[1]);
      const [stem, ans, wrongs, ex] = items[i];
      return enBuilt({ stem, ans, wrongs: wrongs.split('/'), ex }, i * 5 + 1);
    },
  };
}
/** 模板题和小题库合成一个：签名开头 t: 或 p: */
function enMix(a: UpperGen, b: UpperGen): UpperGen {
  return {
    make: (rand) => (rand() < 0.5 ? a.make(rand) : b.make(rand)),
    build: (sig) => (sig.startsWith('t:') ? a.build(sig) : b.build(sig)),
  };
}
