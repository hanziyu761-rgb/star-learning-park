import os
exec(open(__file__.replace("full_lessons.py", "acceptance.py")).read().split("with sync_playwright() as p:")[0])
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get("CHROME") or None, args=["--no-sandbox"])
    ctx = browser.new_context(viewport={"width": 360, "height": 640}, device_scale_factor=2)
    ctx.add_init_script(SPY)
    page = ctx.new_page(); errors=[]
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
    page.goto(BASE); page.wait_for_selector('[data-testid="home"]')
    # 语文全程
    tid(page,"subject-chinese").click(); tid(page,"start-chinese-ri-yue-shui-huo").click()
    for c in ["ri","yue","shui","huo","shan"]: tid(page,f"card-{c}").click()
    click_next(page)
    for c in ["ri","yue","shui","huo"]: drag(page, tid(page,f"drag-{c}"), tid(page,f"target-{c}"))
    click_next(page)
    tid(page,"option-shui").click(); click_next(page)
    tid(page,"option-shan").click(); click_next(page)
    tid(page,"option-yue").click(); click_next(page)
    for c in ["riyue","shanshui","huoshan"]: tid(page,f"card-{c}").click()
    page.screenshot(path=f"{OUT}/20-chinese-words.png"); click_next(page)
    tid(page,"option-huoshan").click(); click_next(page)
    tid(page,"tf-false").click(); page.screenshot(path=f"{OUT}/21-chinese-tf.png"); click_next(page)
    tid(page,"tf-true").click(); click_next(page)
    page.wait_for_selector('[data-testid="lesson-summary"]'); ok("语文课全程完成："+tid(page,"summary-score").inner_text())
    tid(page,"summary-home").click(); page.wait_for_selector('[data-testid="home"]')
    # 英语全程
    tid(page,"subject-english").click(); tid(page,"start-english-fruits").click()
    for w in ["apple","banana","orange","grapes"]: tid(page,f"card-{w}").click()
    click_next(page)
    tid(page,"option-banana").click(); click_next(page)
    tid(page,"option-grapes").click(); click_next(page)
    for i in range(4):
        expect(tid(page,"said-it")).not_to_have_attribute("aria-disabled","true", timeout=5000)
        if i==0: page.screenshot(path=f"{OUT}/22-english-repeat.png")
        tid(page,"said-it").click(); page.wait_for_timeout(200)
    click_next(page); ok("英语跟读 4 个单词")
    for l in ["a","b","o","g"]: tid(page,f"card-{l}").click()
    click_next(page)
    for l in ["a","b","o","g"]: drag(page, tid(page,f"drag-{l}"), tid(page,f"target-{l}"))
    click_next(page); ok("英语字母拖动配对")
    tid(page,"dialogue-play").click(); page.wait_for_timeout(800)
    page.screenshot(path=f"{OUT}/23-english-dialogue.png"); click_next(page)
    tid(page,"option-banana").click(); click_next(page)
    for i in range(4): tid(page,"book-next").click(); page.wait_for_timeout(200)
    page.screenshot(path=f"{OUT}/24-english-book.png"); click_next(page); ok("英语绘本 5 页")
    tid(page,"tf-false").click(); click_next(page)
    page.wait_for_selector('[data-testid="lesson-summary"]'); ok("英语课全程完成："+tid(page,"summary-score").inner_text())
    page.screenshot(path=f"{OUT}/25-english-summary.png")
    tid(page,"summary-home").click(); page.wait_for_selector('[data-testid="home"]')
    page.wait_for_timeout(500); page.screenshot(path=f"{OUT}/26-home-all-done.png", full_page=True)
    ok("首页星星："+tid(page,"total-stars").inner_text().replace("\n"," ")+"；"+tid(page,"lessons-completed").inner_text())
    print("errors", errors)
